# postreboot/hyprland.py
# Clones Impasto to a temporary directory, applies patches from assets/hyprland,
# and runs unattended installation.

import os
import shutil
from core.desktop import _is_hyprland, is_standalone_hyprland
from core.logger import logger
from core.shell import run
from core.config import PROJECT_ROOT


def setup_hyprland(config):
    if not _is_hyprland(config):
        return False

    user = config["system"]["username"]

    # For standalone Hyprland (no GDM), configure TTY1 autologin and autostart
    if is_standalone_hyprland(config):
        logger.info(f"[HYPRLAND] Ensuring TTY1 autologin and Hyprland autostart for {user}")
        run("sudo mkdir -p /etc/systemd/system/getty@tty1.service.d")
        autologin_content = f"""[Service]
ExecStart=
ExecStart=-/sbin/agetty -o '-p -f -- \\\\u' --noclear --autologin {user} %I $TERM
"""
        run("sudo tee /etc/systemd/system/getty@tty1.service.d/autologin.conf > /dev/null", input_data=autologin_content, log_cmd=False)
        run("sudo systemctl daemon-reload")
        run("sudo systemctl disable gdm 2>/dev/null || true", check=False)

        autostart_content = f"""# Automatically launch Hyprland on TTY1 login for standalone Hyprland
if [ -z "$DISPLAY" ] && [ -z "$WAYLAND_DISPLAY" ] && [ "$XDG_VTNR" -eq 1 ] && [ "$(id -un)" = "{user}" ]; then
    if command -v start-hyprland >/dev/null 2>&1; then
        exec start-hyprland
    else
        exec Hyprland
    fi
fi
"""
        run("sudo tee /etc/profile.d/hyprland-autostart.sh > /dev/null", input_data=autostart_content, log_cmd=False)
        run("sudo chmod 755 /etc/profile.d/hyprland-autostart.sh")

    assets_dir = os.path.join(PROJECT_ROOT, "assets", "hyprland")
    patcher = os.path.join(assets_dir, "patch-impasto.py")

    if not os.path.exists(patcher):
        logger.warning(f"[HYPRLAND] Impasto patcher not found at {patcher}, skipping setup.")
        return False

    logger.info("[HYPRLAND] Setting up patched Impasto Hyprland environment...")

    build_dir = "/tmp/impasto_build"
    if os.path.exists(build_dir):
        shutil.rmtree(build_dir)
    os.makedirs(build_dir, exist_ok=True)
    import getpass
    curr_user = getpass.getuser()
    if curr_user != user:
        run(f"sudo chown -R {user}:{user} '{build_dir}'")

    prefix = "" if curr_user == user else f"sudo -H -u {user} "
    try:
        cmd = (
            f"{prefix}python3 '{patcher}' "
            f"--repo '{build_dir}' "
            f"--unattended"
        )
        run(cmd)
        logger.info("[HYPRLAND] Impasto installation and patching completed successfully.")
        apply_custom_keybindings(config)
        return True
    finally:
        if os.path.exists(build_dir):
            shutil.rmtree(build_dir, ignore_errors=True)


def gnome_to_hyprland_binding(binding_str):
    """Converts a GNOME-style binding (e.g. <Control><Alt>p) to Hyprland (CTRL + ALT + P)."""
    if not binding_str:
        return ""
    if "<" not in binding_str and ("+" in binding_str or "," in binding_str):
        return binding_str.strip()

    mapping = {
        "<control>": "CTRL",
        "<ctrl>": "CTRL",
        "<alt>": "ALT",
        "<shift>": "SHIFT",
        "<super>": "SUPER",
        "<primary>": "CTRL",
        "<mod4>": "SUPER",
    }
    import re
    mods = []
    rest = binding_str
    tags = re.findall(r"<[^>]+>", binding_str)
    for tag in tags:
        lower_tag = tag.lower()
        if lower_tag in mapping:
            mods.append(mapping[lower_tag])
        rest = rest.replace(tag, "")

    key = rest.strip()
    if len(key) == 1:
        key = key.upper()
    elif key.lower() == "return":
        key = "Return"
    elif key.lower() == "space":
        key = "Space"
    elif key.lower() == "tab":
        key = "Tab"

    return " + ".join(mods + [key]) if key else " + ".join(mods)


def apply_custom_keybindings(config):
    """Generates ~/.config/hypr/custom-keybindings.lua from secrets.yaml keybindings."""
    postconfig = config.get("postconfig", {})
    # Look for hyprland keybindings first, fallback to generic or gnome keybindings
    kb_cfg = (
        postconfig.get("hyprland", {}).get("keybindings")
        or postconfig.get("keybindings")
        or postconfig.get("gnome", {}).get("keybindings")
    )
    if not kb_cfg or not kb_cfg.get("enabled"):
        return False

    bindings = kb_cfg.get("bindings", [])
    if not bindings:
        return False

    user = config["system"]["username"]
    hypr_dir = f"/home/{user}/.config/hypr"
    os.makedirs(hypr_dir, exist_ok=True)
    custom_kb_file = os.path.join(hypr_dir, "custom-keybindings.lua")

    lines = [
        "-- ╭──────────────────────────────────────────────────────────────────────────╮",
        "-- │   Custom keybindings dynamically generated by arch_install               │",
        "-- │   Source: config/secrets/secrets.yaml[.age]                              │",
        "-- ╰──────────────────────────────────────────────────────────────────────────╯",
        "",
    ]

    for b in bindings:
        name = b.get("name", "Custom Binding")
        cmd = b.get("command", "")
        raw_bind = b.get("binding", "")
        if not cmd or not raw_bind:
            continue
        hypr_bind = gnome_to_hyprland_binding(raw_bind)
        lines.append(f'hl.bind("{hypr_bind}", hl.dsp.exec_cmd([[{cmd}]]), {{ description = "{name}" }})')

    lines.append("")
    content = "\n".join(lines)

    logger.info(f"[HYPRLAND] Writing {len(bindings)} custom keybindings to {custom_kb_file}")
    with open(custom_kb_file, "w", encoding="utf-8") as f:
        f.write(content)

    try:
        import pwd
        pw = pwd.getpwnam(user)
        os.chown(custom_kb_file, pw.pw_uid, pw.pw_gid)
    except Exception:
        pass
    try:
        os.chmod(custom_kb_file, 0o600)
    except Exception:
        pass

    # Reload hyprland if active
    run("hyprctl reload", check=False, log_cmd=False)
    return True
